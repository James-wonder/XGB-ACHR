# --- 辅助函数：自动解析您粘贴的数据 ---
def parse_roc_data(data_string):
    fpr_list = []
    tpr_list = []
    for line in data_string.strip().splitlines():
        try:
            fpr, tpr = map(float, line.split(','))
            fpr_list.append(fpr)
            tpr_list.append(tpr)
        except ValueError:
            continue
    return {'fpr': fpr_list, 'tpr': tpr_list}

